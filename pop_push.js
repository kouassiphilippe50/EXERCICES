// push et pop : permet d'ajouter et retirer un element a la fin du tableau
let fruit= [`orange,banane,raisin`];
fruit.push("mangue");// utiliser "push" pour ajouter un element ou plusieurs elements au tableau "fruit"
console.log(fruit);
fruit.pop();// utiliser "pop" pour retirer le dernier element;
console.log(fruit);

// unshift/shift : permet d'ajouter et retirer un element au debut du tableau
fruit.unshift("fraise");
console.log(fruit);// unshift : ajouter

fruit.shift(fruit);// shift : retirer


